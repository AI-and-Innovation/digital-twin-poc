def postprocess(layout: dict) -> None:
    """Fit L1 to the DIAL plan: snap nodes, gates and checkpoints to open floor, then route every walkway edge that
    cuts through a wall, shop or void round it on open floor, and keep the dwell areas to open floor."""
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from dial_plan import CONNECTORS, Plan

    plan = Plan(FRAME, doors=ASSUMED_DOORS)
    nodes = {n["id"]: n for n in layout["walkways"]["nodes"]}
    for n in nodes.values():
        if n["floor"] == PLAN_FLOOR:
            n["x"], n["y"] = plan.snap(n["x"], n["y"])
    for g in layout["gates"]:   # a few OSM gate points sit well outside the drawn piers: look further for them
        n = nodes[g["gate_id"]]
        n["x"], n["y"] = plan.snap(n["x"], n["y"], max_m=60.0)
        g["x"], g["y"] = n["x"], n["y"]
    for t in layout["touchpoints"].values():
        if t["floor"] == PLAN_FLOOR:
            t["x"], t["y"] = plan.snap(t["x"], t["y"])

    edges = []
    for a, b in layout["walkways"]["edges"]:
        na, nb = nodes[a], nodes[b]
        if na["floor"] != PLAN_FLOOR or nb["floor"] != PLAN_FLOOR \
                or not plan.crossings(na["x"], na["y"], nb["x"], nb["y"]):
            edges.append([a, b])
            continue
        corners = plan.route(na["x"], na["y"], nb["x"], nb["y"])
        if corners is None:   # the pier heads: only across the ramp / escalator polygons
            corners = plan.route(na["x"], na["y"], nb["x"], nb["y"], allow=CONNECTORS)
        if corners is None:   # no way round within reach: keep the straight link (the check script lists it)
            edges.append([a, b])
            continue
        chain = [a]
        for k, (x, y) in enumerate(corners, start=1):
            nodes[f"{a}~{b}.{k}"] = {"id": f"{a}~{b}.{k}", "x": x, "y": y, "floor": PLAN_FLOOR}
            chain.append(f"{a}~{b}.{k}")
        chain.append(b)
        edges += [list(e) for e in zip(chain, chain[1:])]
    layout["walkways"] = {"nodes": list(nodes.values()), "edges": edges}

    # gate holding areas: passengers wait on a ring round an open spot 8 m into the pier from the gate
    adjacency: dict[str, str] = {}
    for a, b in edges:
        adjacency.setdefault(a, b)
        adjacency.setdefault(b, a)
    for g in layout["gates"]:
        n = nodes[adjacency[g["gate_id"]]]
        d = math.hypot(n["x"] - g["x"], n["y"] - g["y"]) or 1.0
        x, y = g["x"] + (n["x"] - g["x"]) * 8 / d, g["y"] + (n["y"] - g["y"]) * 8 / d
        for r in (5.0, 4.0, 3.0, 2.0):
            hx, hy = plan.snap(x, y, max_m=10.0, radius=r)
            if plan.clear(hx, hy, r) and plan.clear(hx, hy, r / 2):
                break
        g["holding"] = {"x": hx, "y": hy, "radius_m": r}

    # dwell and spawn areas: keep only the open-floor 3 m cells, so random points never land in a shop or void
    for area in layout["areas"].values():
        if area["floor"] != PLAN_FLOOR:
            continue
        cells = []
        for poly in area["polygons"]:
            xs, ys = [p[0] for p in poly], [p[1] for p in poly]
            cell = min(AREA_CELL_M, max(xs) - min(xs), max(ys) - min(ys))
            x = min(xs)
            while x + cell <= max(xs) + 1e-6:
                y = min(ys)
                while y + cell <= max(ys) + 1e-6:
                    if plan.clear(x + cell / 2, y + cell / 2, radius=cell / 2):
                        cells.append(box(round(x, 1), round(y, 1), round(x + cell, 1), round(y + cell, 1)))
                    y += cell
                x += cell
        area["polygons"] = cells or area["polygons"]
    layout["floor_plans"] = {PLAN_FLOOR: {"file": "dial_t3_departures_plan.geojson", "source": "DIAL via GeoKno",
                                          "received": "2026-10-15", "level_id": "2542", "floor_id": 66214,
                                          "assumed_doors": [list(d) for d in ASSUMED_DOORS]}}


