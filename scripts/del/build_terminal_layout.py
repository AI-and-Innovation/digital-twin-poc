def _arm(prefix: str, points: list[tuple[float, float]], floor: str, step: float = 60.0):
    """Walkway nodes every ``step`` metres along a polyline, and the edges between them."""
    import math
    nodes, edges = [], []
    for (x0, y0), (x1, y1) in zip(points, points[1:]):
        n = max(1, round(math.hypot(x1 - x0, y1 - y0) / step))
        for k in range(n + (1 if (x1, y1) == points[-1] else 0)):
            t = k / n
            nodes.append((f"{prefix}{len(nodes) + 1:02d}", round(x0 + (x1 - x0) * t, 1),
                          round(y0 + (y1 - y0) * t, 1), floor))
    edges = [(a[0], b[0]) for a, b in zip(nodes, nodes[1:])]
    return nodes, edges


