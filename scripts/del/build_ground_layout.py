def _landside(x: float, y: float) -> bool:
    return (y > 120 and -330 < x < 420) or y > 270


def side_of(tags: dict, pts: list[list[float]]) -> str | None:
    if tags.get("highway") == "service" and not any(_landside(x, y) for x, y in pts) and min(p[1] for p in pts) > -800:
        return "airside"
    if all(_landside(x, y) for x, y in pts) and tags.get("layer") != "-2":
        return "landside"
    return None


def stand_flow(x: float, y: float) -> str:
    return "int" if x < 0 else "dom"


# OSM maps hardly any apron roads around T3, and its few parking_position nodes belong to the
# T2 apron. So airside is SCHEMATIC here: one contact stand per OSM gate (70 m out from the
# gate) and a head-of-stand service road 32 m either side of each pier's centre line, joined
# by a cross road behind the processor and spurs to the depots and service points.
STAND_OFFSET_M = 70.0
ROAD_OFFSET_M = 32.0
CROSS_ROAD_Y = -175.0


def extend(layout: dict) -> None:
    import json
    import math

    import importlib.util
    spec_path = ROOT / "scripts" / "del" / "build_terminal_layout.py"
    mod_spec = importlib.util.spec_from_file_location("del_terminal", spec_path)
    terminal = importlib.util.module_from_spec(mod_spec)
    mod_spec.loader.exec_module(terminal)
    t = json.loads((ROOT / "config/del/terminal_layout.json").read_text(encoding="utf-8"))

    # drop the stray OSM airside bits (disconnected, outside the T3 apron)
    keep = [e for e in layout["roads"]["edges"] if e[6] != "airside"]
    used = {e[0] for e in keep} | {e[1] for e in keep}
    nodes = [n for n in layout["roads"]["nodes"] if n["id"] in used]
    edges = keep
    added: list[dict] = []

    def node(x: float, y: float) -> str:
        nid = f"a{len(added) + 1}"
        added.append({"id": nid, "x": round(x, 1), "y": round(y, 1), "side": "airside"})
        return nid

    def link(a: str, b: str) -> None:
        pa = next(n for n in added if n["id"] == a)
        pb = next(n for n in added if n["id"] == b)
        length = round(math.hypot(pb["x"] - pa["x"], pb["y"] - pa["y"]), 1)
        name = "Apron service road (schematic)"
        edges.extend([[a, b, length, AIRSIDE_KMH, "L0", name, "airside", None],
                      [b, a, length, AIRSIDE_KMH, "L0", name, "airside", None]])

    def road(points, step=40.0) -> list[str]:
        ids = []
        for (x0, y0), (x1, y1) in zip(points, points[1:]):
            n = max(1, round(math.hypot(x1 - x0, y1 - y0) / step))
            for k in range(n):
                ids.append(node(x0 + (x1 - x0) * k / n, y0 + (y1 - y0) * k / n))
        ids.append(node(*points[-1]))
        for a, b in zip(ids, ids[1:]):
            link(a, b)
        return ids

    def offset(line, d):
        out = []
        for i, (x, y) in enumerate(line):
            a = line[max(i - 1, 0)]
            b = line[min(i + 1, len(line) - 1)]
            dx, dy = b[0] - a[0], b[1] - a[1]
            L = math.hypot(dx, dy) or 1.0
            out.append((x - dy / L * d, y + dx / L * d))
        return out

    roads = []
    for line in (terminal.INT_DOWN, terminal.INT_SIDE, terminal.DOM_DOWN, terminal.DOM_SIDE):
        for d in (ROAD_OFFSET_M, -ROAD_OFFSET_M):
            roads.append(road(offset(line, d)))
    roads.append(road([(-240, CROSS_ROAD_Y), (240, CROSS_ROAD_Y)]))

    def xy(nid):
        n = next(n for n in added if n["id"] == nid)
        return n["x"], n["y"]

    def nearest(x, y, exclude=()):
        best = min((n for n in added if n["id"] not in exclude), key=lambda n: (n["x"] - x) ** 2 + (n["y"] - y) ** 2)
        return best["id"]

    # join road ends to the nearest node of another road within 140 m
    for ids in roads:
        for end in (ids[0], ids[-1]):
            x, y = xy(end)
            other = min((n for r in roads if r is not ids for n in r),
                        key=lambda n: (xy(n)[0] - x) ** 2 + (xy(n)[1] - y) ** 2)
            ox, oy = xy(other)
            if math.hypot(ox - x, oy - y) < 140:
                link(end, other)
    # spurs to the depots and service points
    for x, y in [tuple(d["near"]) for d in DEPOTS] + list(SERVICE_POINTS.values()):
        target = nearest(x, y)
        link(node(x, y), target)

    # stands: one per contact gate, out from the pier
    walk = {n["id"]: n for n in t["walkways"]["nodes"]}
    adjacent = {}
    for e in t["walkways"]["edges"]:
        adjacent.setdefault(e[0], []).append(e[1])
        adjacent.setdefault(e[1], []).append(e[0])
    stands = []
    for g in t["gates"]:
        spine = walk[adjacent[g["gate_id"]][0]]
        dx, dy = g["x"] - spine["x"], g["y"] - spine["y"]
        L = math.hypot(dx, dy) or 1.0
        number = g["gate_id"].rsplit("-", 1)[1]
        stands.append({"stand_id": f"{ID_PREFIX}-STAND-{int(number):02d}", "osm_ref": None, "gate_id": g["gate_id"],
                       "x": round(g["x"] + dx / L * STAND_OFFSET_M, 1), "y": round(g["y"] + dy / L * STAND_OFFSET_M, 1),
                       "flow": g["flow"]})
    layout["roads"]["nodes"] = nodes + added
    layout["roads"]["edges"] = edges
    layout["stands"] = stands
    layout["_note"] += (" Delhi airside is SCHEMATIC: OSM maps almost no T3 apron roads or stands, so stands are "
                        "placed 70 m out from each gate lounge and apron service roads run along the piers.")


